/**
 * Generates js/firebase-config.js from environment variables.
 * Used locally (via .env) and on Vercel (Project → Settings → Environment Variables).
 */
const fs = require("fs");
const path = require("path");

try {
  require("dotenv").config({ path: path.join(__dirname, "..", ".env") });
  require("dotenv").config({ path: path.join(__dirname, "..", ".env.local") });
} catch {
  /* dotenv optional until npm install */
}

const KEYS = [
  "FIREBASE_API_KEY",
  "FIREBASE_AUTH_DOMAIN",
  "FIREBASE_DATABASE_URL",
  "FIREBASE_PROJECT_ID",
  "FIREBASE_STORAGE_BUCKET",
  "FIREBASE_MESSAGING_SENDER_ID",
  "FIREBASE_APP_ID",
];

function env(name) {
  return (process.env[name] || "").trim();
}

const values = Object.fromEntries(KEYS.map((k) => [k, env(k)]));
const missing = KEYS.filter((k) => !values[k]);
const enabled = missing.length === 0;

const outPath = path.join(__dirname, "..", "js", "firebase-config.js");
const config = {
  enabled,
  apiKey: values.FIREBASE_API_KEY,
  authDomain: values.FIREBASE_AUTH_DOMAIN,
  databaseURL: values.FIREBASE_DATABASE_URL,
  projectId: values.FIREBASE_PROJECT_ID,
  storageBucket: values.FIREBASE_STORAGE_BUCKET,
  messagingSenderId: values.FIREBASE_MESSAGING_SENDER_ID,
  appId: values.FIREBASE_APP_ID,
};

const file = `/* Auto-generated by scripts/generate-firebase-config.js — do not edit manually */
window.FIREBASE_CONFIG = ${JSON.stringify(config, null, 2)};
`;

fs.writeFileSync(outPath, file, "utf8");

if (enabled) {
  console.log("✓ firebase-config.js written (Live mode enabled)");
} else {
  console.warn("⚠ firebase-config.js written with enabled: false");
  console.warn("  Missing variables:", missing.join(", "));
  console.warn("  Add them in Vercel → Settings → Environment Variables, then redeploy.");
}
